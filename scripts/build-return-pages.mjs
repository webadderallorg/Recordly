// Email clients need concrete inline values instead of modern theme variables.
// Snapshot the installed HeroUI theme and large Button; do not approximate them.
const declarations = (rule) =>
	Object.fromEntries(
		rule.nodes.filter((node) => node.type === "decl").map((node) => [node.prop, node.value]),
	);
const light = {};
const dark = {};
variables.walkRules((rule) => {
	const selectors = rule.selector.split(",").map((value) => value.trim());
	if (selectors.includes(":root")) Object.assign(light, declarations(rule));
	if (selectors.includes('[data-theme="dark"]')) Object.assign(dark, declarations(rule));
});
const compiled = postcss.parse(result.css);
const primitives = {};
const button = {};
const largeButton = {};
compiled.walkRules((rule) => {
	const selectors = rule.selector.split(",").map((value) => value.trim());
	if (selectors.includes(":root") || selectors.includes(":host"))
		Object.assign(primitives, declarations(rule));
	// Use base/touch sizes, excluding responsive and reduced-motion overrides.
	let parent = rule.parent;
	while (parent && parent.type !== "root") {
		if (parent.type === "atrule" && parent.name === "media") return;
		parent = parent.parent;
	}
	if (rule.selector === ".button") Object.assign(button, declarations(rule));
	if (rule.selector === ".button--lg") Object.assign(largeButton, declarations(rule));
});
function resolve(value, tokens, depth = 0) {
	if (!value || depth > 10) throw new Error("Unresolved HeroUI email token");
	return value.replace(/var\((--[a-z0-9-]+)\)/gi, (_match, key) =>
		resolve(tokens[key], tokens, depth + 1),
	);
}
function pixels(value) {
	const resolved = resolve(value, { ...primitives, ...light }).replace(
		/calc\(([\d.]+)(rem|px)\s*\*\s*([\d.]+)\)/g,
		(_match, amount, unit, multiplier) => `${Number(amount) * Number(multiplier)}${unit}`,
	);
	const match = resolved.match(/^([\d.]+)(rem|px)$/);
	if (!match) throw new Error(`Unsupported HeroUI email dimension: ${resolved}`);
	return Number(match[1]) * (match[2] === "rem" ? 16 : 1);
}
function color(key, tokens) {
	const raw = resolve(tokens[key], tokens);
	const converted = transform({
		filename: "email-theme.css",
		code: Buffer.from(`.email{color:${raw}}`),
		targets: { ie: 11 << 16 },
		minify: true,
	}).code.toString();
	const declaration = postcss
		.parse(converted)
		.first.nodes.find((node) => node.type === "decl" && node.prop === "color");
	if (!declaration || !/^#[a-f0-9]{3,8}$/i.test(declaration.value))
		throw new Error(`No email-safe HeroUI colour for ${key}`);
	return declaration.value;
}
function palette(tokens) {
	return Object.fromEntries(
		["surface", "foreground", "muted", "accent", "accent-foreground", "link"].map((key) => [
			key,
			color(`--${key}`, tokens),
		]),
	);
}
const heroVersion = JSON.parse(
	await readFile(new URL("node_modules/@heroui/styles/package.json", root), "utf8"),
).version;
const emailTheme = {
	source: `@heroui/styles ${heroVersion}, large primary Button`,
	fontFamily: "'DM Sans',-apple-system,BlinkMacSystemFont,'Segoe UI',Arial,sans-serif",
	light: palette(light),
	dark: palette({ ...light, ...dark }),
	button: {
		radius: pixels(button["border-radius"]),
		height: pixels(largeButton.height),
		fontSize: pixels(largeButton["font-size"]),
		fontWeight: Number(resolve(button["font-weight"], primitives)),
		paddingInline: pixels(button["padding-inline"]),
	},
};
await writeFile(
	new URL("services/email/theme.generated.mjs", root),
	`// Generated by npm run return-pages:build from the installed HeroUI sources.\nexport const emailTheme = ${JSON.stringify(emailTheme, null, "\t")};\n`,
);
console.log(`Built email-safe theme from ${emailTheme.source}.`);
